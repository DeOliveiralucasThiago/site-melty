import { sanitizarDescricao as s } from "../functions/_lib/html.js";
let ok = 0, bad = 0;
const t = (nome, entrada, esperado) => { const r = s(entrada); const passou = typeof esperado === "function" ? esperado(r) : r === esperado; passou ? ok++ : bad++; console.log(passou ? "OK  " : "FALHA", nome, passou ? "" : `\n     got: ${r}`); };
t("texto simples vira parágrafos", "Linha 1\nLinha 2\n\nOutro", "<p>Linha 1<br>Linha 2</p><p>Outro</p>");
t("escapa HTML em texto simples", "a < b & c", "<p>a &lt; b &amp; c</p>");
t("b/i viram strong/em", "<p><b>oi</b> <i>tu</i></p>", "<p><strong>oi</strong> <em>tu</em></p>");
t("div vira p", "<div>um</div><div>dois</div>", "<p>um</p><p>dois</p>");
t("remove script com conteúdo", "<p>ok</p><script>alert(1)</script><p>fim</p>", "<p>ok</p><p>fim</p>");
t("remove onerror em img", '<p>x</p><img src=x onerror=alert(1)>', "<p>x</p>");
t("remove atributos de p", '<p onclick="x()" style="color:red">a</p>', "<p>a</p>");
t("link https permitido", '<a href="https://exemplo.com/a?b=1&amp;c=2">x</a>', (r) => r === '<a href="https://exemplo.com/a?b=1&amp;c=2" target="_blank" rel="noopener noreferrer">x</a>');
t("link javascript: removido (texto fica)", '<a href="javascript:alert(1)">clique</a>', "clique");
t("link http (não https) removido", '<a href="http://x.com">x</a>', "x");
t("link com data: removido", '<a href="data:text/html,<script>1</script>">x</a>', (r) => !r.includes("<a") && !r.includes("<script"));
t("span com cor da marca", '<span class="cor-vinho">oi</span>', '<span class="cor-vinho">oi</span>');
t("span com classe estranha removido", '<span class="x" style="color:red">oi</span>', "oi");
t("style inline removido", '<span style="font-size:99px">oi</span>', "oi");
t("lista", "<ul><li>a</li><li>b</li></ul>", "<ul><li>a</li><li>b</li></ul>");
t("subtítulo h2/h1 → h3", "<h1>T</h1><h2>U</h2>", "<h3>T</h3><h3>U</h3>");
t("fecha tags abertas", "<p><strong>aberto", "<p><strong>aberto</strong></p>");
t("ignora fechamento solto", "texto</strong></p>", "texto");
t("comentário removido", "<p>a<!-- <script> -->b</p>", "<p>ab</p>");
t("parágrafo vazio removido", "<p>a</p><p><br></p><p></p><p>b</p>", "<p>a</p><p>b</p>");
t("entidades decodificadas e reescapadas", "<p>a&nbsp;&amp;&lt;b</p>", "<p>a &amp;&lt;b</p>");
t("iframe e svg descartados", '<iframe src="x"></iframe><svg onload=alert(1)><circle/></svg><p>ok</p>', "<p>ok</p>");
t("tag quebrada vira texto", "<p>a <b</p>", (r) => !r.includes("<b"));
t("p dentro de p não aninha", "<p>a<p>b</p></p>", "<p>a</p><p>b</p>");
t("idempotente", s('<p><strong>a</strong> <span class="cor-rosa">b</span></p>'), s(s('<p><strong>a</strong> <span class="cor-rosa">b</span></p>')));
t("entrada vazia/null", null, "");

t("cor vinho via style rgb", '<span style="color: rgb(181, 33, 65);">x</span>', '<span class="cor-vinho">x</span>');
t("cor rosa via style hex", '<span style="color:#F2808A">x</span>', '<span class="cor-rosa">x</span>');
t("marca-texto via style", '<span style="background-color: rgb(255, 217, 217);">x</span>', '<span class="marca-rosa">x</span>');
t("cor + fundo juntos", '<span style="color:#B52141;background-color:#FFD9D9">x</span>', (r) => /^<span class="(cor-vinho marca-rosa|marca-rosa cor-vinho)">x<\/span>$/.test(r));
t("cor fora da paleta é descartada", '<span style="color: rgb(255, 0, 0);">x</span>', "x");
t("transparente (sem cor) é descartado", '<span style="color: rgb(43, 34, 36); background-color: transparent;">x</span>', "x");
t("style malicioso descartado", '<span style="color:red;background:url(javascript:alert(1))">x</span>', "x");
t("negrito + cor aninhados", '<strong><span style="color: rgb(181, 33, 65);">oi</span></strong>', '<strong><span class="cor-vinho">oi</span></strong>');
console.log(`\n${ok} ok, ${bad} falhas`); process.exit(bad ? 1 : 0);
